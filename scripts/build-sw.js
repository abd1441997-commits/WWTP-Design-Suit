'use strict';
// Generates www/sw.js: a cache-first service worker whose cache name changes whenever any app file changes.
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const www = path.resolve(__dirname, '..', 'www');
const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
const files = walk(www).map(f => path.relative(www, f).split(path.sep).join('/'))
  .filter(f => f !== 'sw.js' && !f.endsWith('.map')).sort();
const h = crypto.createHash('sha256');
files.forEach(f => { h.update(f); h.update(fs.readFileSync(path.join(www, f))); });
const version = h.digest('hex').slice(0, 12);
const assets = ['./'].concat(files.map(f => './' + f));
fs.writeFileSync(path.join(www, 'sw.js'), `/* Generated by scripts/build-sw.js - do not edit. */
const CACHE = 'wwtp-suite-${version}';
const ASSETS = ${JSON.stringify(assets, null, 1)};
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('wwtp-suite-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req).then(res => {
    if (res && res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
    return res;
  }).catch(() => req.mode === 'navigate' ? caches.match('./index.html') : Response.error())));
});
`);
console.log('sw.js generated:', assets.length, 'assets, cache wwtp-suite-' + version);
